    private static Border WrapPanelBorder(UIElement child)
        => new()
        {
            Background = Brushes.White,
            BorderBrush = new SolidColorBrush(Color.FromRgb(224, 229, 238)),
            BorderThickness = new Thickness(1),
            CornerRadius = new CornerRadius(7),
            ClipToBounds = true,
            Child = child
        };

    private void RefreshTopics()
    {
        var query = (_searchBox?.Text ?? string.Empty).Trim();
        IEnumerable<FaqTopic> filtered = _topics;

        if (!string.Equals(_category, "Все разделы", StringComparison.Ordinal))
            filtered = filtered.Where(x => x.Category == _category);

        if (query.Length > 0)
        {
            filtered = filtered.Where(x =>
                x.Title.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                x.Body.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                x.Keywords.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                x.Category.Contains(query, StringComparison.OrdinalIgnoreCase));
        }

        var list = filtered.ToList();
        _topicList.ItemsSource = list;
        _resultText.Text = $"Найдено разделов: {list.Count}";

        if (list.Count > 0)
            _topicList.SelectedIndex = 0;
        else
            RenderEmpty();
    }

    private void RenderEmpty()
    {
        _detailsPanel.Children.Clear();
        _detailsPanel.Children.Add(new TextBlock
        {
            Text = "Ничего не найдено. Попробуйте другой запрос.",
            Foreground = Brushes.DimGray,
            Margin = new Thickness(0, 8, 0, 0)
        });
    }

    private void RenderSelectedTopic()
    {
        if (_topicList.SelectedItem is not FaqTopic topic)
        {
            RenderEmpty();
            return;
        }

        _detailsPanel.Children.Clear();
        _detailsPanel.Children.Add(new TextBlock
        {
            Text = topic.Category,
            Foreground = new SolidColorBrush(Color.FromRgb(54, 111, 214)),
            FontWeight = FontWeights.SemiBold,
            Margin = new Thickness(0, 0, 0, 5)
        });
        _detailsPanel.Children.Add(new TextBlock
        {
            Text = topic.Title,
            FontSize = 21,
            FontWeight = FontWeights.SemiBold,
            Foreground = new SolidColorBrush(Color.FromRgb(24, 31, 45)),
            TextWrapping = TextWrapping.Wrap,
            Margin = new Thickness(0, 0, 0, 14)
        });

        foreach (var paragraph in topic.Body.Split("\n\n", StringSplitOptions.RemoveEmptyEntries))
        {
            _detailsPanel.Children.Add(new TextBlock
            {
                Text = paragraph.Trim(),
                TextWrapping = TextWrapping.Wrap,
                FontSize = 14,
                LineHeight = 21,
                Margin = new Thickness(0, 0, 0, 11),
                Foreground = new SolidColorBrush(Color.FromRgb(48, 55, 68))
            });
        }
    }

